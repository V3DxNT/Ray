//go:embed templates/*.txt
var ignoreTemplates embed.FS

type IgnorePlan struct {
	TargetDir         string
	DetectedStacks    []string
	GitignoreContent  string
	DockerContent     string
	GitignoreRules    int
	DockerRules       int
	GitignoreExisted  bool
	DockerExisted     bool
}

var (
	ignoreStacksFlag  []string
	ignoreForce       bool
	ignoreAppend      bool
	ignoreGitOnly     bool
	ignoreDockerOnly  bool
	ignoreDryRun      bool
)

var ignoreCmd = &cobra.Command{
	Use:   "ignore [path]",
	Short: "Generate composable .gitignore and .dockerignore files for polyglot codebases",
	Run:   runIgnore,
}

func init() {
	RootCmd.AddCommand(ignoreCmd)
	ignoreCmd.Flags().StringSliceVarP(&ignoreStacksFlag, "stack", "s", []string{}, "Explicit stacks to include (e.g. go,node,python)")
	ignoreCmd.Flags().BoolVarP(&ignoreForce, "force", "f", false, "Overwrite existing .gitignore and .dockerignore without prompting")
	ignoreCmd.Flags().BoolVarP(&ignoreAppend, "append", "a", false, "Append generated rules to existing files")
	ignoreCmd.Flags().BoolVar(&ignoreGitOnly, "git", false, "Only generate .gitignore")
	ignoreCmd.Flags().BoolVar(&ignoreDockerOnly, "docker", false, "Only generate .dockerignore")
	ignoreCmd.Flags().BoolVar(&ignoreDryRun, "dry-run", false, "Preview generated ignore rules without writing to disk")
}

func runIgnore(cmd *cobra.Command, args []string) {
	reader := bufio.NewReader(os.Stdin)

	target := "."
	if len(args) > 0 {
		target = args[0]
	}

	absPath, err := filepath.Abs(target)
	if err != nil {
		color.Red("Failed to resolve target directory: %v", err)
		return
	}

	info, err := os.Stat(absPath)
	if err != nil {
		color.Red("Directory does not exist: %v", err)
		return
	}
	if !info.IsDir() {
		color.Red("Target path must be a directory")
		return
	}

	stacks := resolveIgnoreStacks(absPath, ignoreStacksFlag)
	if len(stacks) == 0 {
		stacks = []string{"base"}
	}

	plan := buildIgnorePlan(absPath, stacks)
	renderIgnorePlanBox(plan)

	if ignoreDryRun {
		color.Yellow("Dry-run active: no files were written to disk.")
		return
	}

	gitPath := filepath.Join(absPath, ".gitignore")
	dockerPath := filepath.Join(absPath, ".dockerignore")

	if !ignoreDockerOnly {
		writeIgnoreTargetFile(gitPath, plan.GitignoreContent, plan.GitignoreExisted, ignoreForce, ignoreAppend, reader, ".gitignore")
	}

	if !ignoreGitOnly {
		writeIgnoreTargetFile(dockerPath, plan.DockerContent, plan.DockerExisted, ignoreForce, ignoreAppend, reader, ".dockerignore")
	}

	fmt.Println()
	color.HiGreen("✔ Ignore engine generation complete!")
}

func resolveIgnoreStacks(root string, manualStacks []string) []string {
	if len(manualStacks) > 0 {
		var res []string
		for _, s := range manualStacks {
			cleaned := strings.ToLower(strings.TrimSpace(s))
			if cleaned != "" {
				res = append(res, cleaned)
			}
		}
		return res
	}

	stackSet := make(map[string]bool)

	var components []DetectedComponent
	scanSubprojects(root, root, 0, &components)

	for _, c := range components {
		st := strings.ToLower(c.Stack)
		if strings.Contains(st, "go lang") {
			stackSet["go"] = true
		}
		if strings.Contains(st, "node") || strings.Contains(st, "react") || strings.Contains(st, "next") || strings.Contains(st, "vite") {
			stackSet["node"] = true
		}
		if strings.Contains(st, "python") {
			stackSet["python"] = true
		}
		if strings.Contains(st, "rust") {
			stackSet["rust"] = true
		}
		if strings.Contains(st, "java") {
			stackSet["java"] = true
		}
		if strings.Contains(st, "c++") || strings.Contains(st, "cmake") {
			stackSet["cpp"] = true
		}
	}

	if fileExists(filepath.Join(root, "go.mod")) {
		stackSet["go"] = true
	}
	if fileExists(filepath.Join(root, "package.json")) {
		stackSet["node"] = true
	}
	if fileExists(filepath.Join(root, "requirements.txt")) || fileExists(filepath.Join(root, "pyproject.toml")) {
		stackSet["python"] = true
	}
	if fileExists(filepath.Join(root, "Cargo.toml")) {
		stackSet["rust"] = true
	}
	if fileExists(filepath.Join(root, "pom.xml")) || fileExists(filepath.Join(root, "build.gradle")) {
		stackSet["java"] = true
	}
	if fileExists(filepath.Join(root, "CMakeLists.txt")) {
		stackSet["cpp"] = true
	}

	var sorted []string
	for k := range stackSet {
		sorted = append(sorted, k)
	}
	sort.Strings(sorted)
	return sorted
}

func buildIgnorePlan(root string, stacks []string) IgnorePlan {
	var gitBuf bytes.Buffer
	var dockerBuf bytes.Buffer

	gitBuf.WriteString("# =============================================================================\n")
	gitBuf.WriteString("# Generated by Ray Polyglot Engine (https://github.com/V3DxNT/Ray)\n")
	gitBuf.WriteString("# =============================================================================\n\n")

	baseData, err := ignoreTemplates.ReadFile("templates/base.txt")
	if err == nil {
		gitBuf.Write(baseData)
		gitBuf.WriteString("\n\n")
	}

	for _, stack := range stacks {
		fileName := fmt.Sprintf("templates/%s.txt", stack)
		data, err := ignoreTemplates.ReadFile(fileName)
		if err == nil {
			title := formatStackTitle(stack)
			gitBuf.WriteString(fmt.Sprintf("# =============================================================================\n# %s\n# =============================================================================\n", title))
			gitBuf.Write(data)
			gitBuf.WriteString("\n\n")
		}
	}

	dockerData, err := ignoreTemplates.ReadFile("templates/dockerignore.txt")
	if err == nil {
		dockerBuf.WriteString("# =============================================================================\n")
		dockerBuf.WriteString("# Generated by Ray Polyglot Engine (https://github.com/V3DxNT/Ray)\n")
		dockerBuf.WriteString("# =============================================================================\n\n")
		dockerBuf.Write(dockerData)
		dockerBuf.WriteString("\n\n")
	}

	for _, stack := range stacks {
		switch stack {
		case "go":
			dockerBuf.WriteString("# Go Specific Exclusions\nbin/\n*.exe\nvendor/\n\n")
		case "node":
			dockerBuf.WriteString("# Node Specific Exclusions\nnode_modules/\n.next/\n.nuxt/\n.cache/\n\n")
		case "python":
			dockerBuf.WriteString("# Python Specific Exclusions\n__pycache__/\n*.pyc\n.venv/\nvenv/\n\n")
		case "rust":
			dockerBuf.WriteString("# Rust Specific Exclusions\ntarget/\n\n")
		case "java":
			dockerBuf.WriteString("# Java Specific Exclusions\ntarget/\n.gradle/\nbuild/\n\n")
		case "cpp":
			dockerBuf.WriteString("# C/C++ Specific Exclusions\nbuild/\nCMakeFiles/\n\n")
		}
	}

	gitStr := cleanIgnoreOutput(gitBuf.String())
	dockerStr := cleanIgnoreOutput(dockerBuf.String())

	gitPath := filepath.Join(root, ".gitignore")
	dockerPath := filepath.Join(root, ".dockerignore")

	_, gitExists := os.Stat(gitPath)
	_, dockerExists := os.Stat(dockerPath)

	return IgnorePlan{
		TargetDir:        root,
		DetectedStacks:   stacks,
		GitignoreContent: gitStr,
		DockerContent:    dockerStr,
		GitignoreRules:   countIgnoreRules(gitStr),
		DockerRules:      countIgnoreRules(dockerStr),
		GitignoreExisted: gitExists == nil,
		DockerExisted:    dockerExists == nil,
	}
}

func countIgnoreRules(s string) int {
	cnt := 0
	lines := strings.Split(s, "\n")
	for _, l := range lines {
		trimmed := strings.TrimSpace(l)
		if trimmed != "" && !strings.HasPrefix(trimmed, "#") {
			cnt++
		}
	}
	return cnt
}

func cleanIgnoreOutput(s string) string {
	var res []string
	lines := strings.Split(s, "\n")
	lastEmpty := false
	for _, l := range lines {
		trimmed := strings.TrimRight(l, " \r\t")
		if trimmed == "" {
			if !lastEmpty {
				res = append(res, "")
				lastEmpty = true
			}
		} else {
			res = append(res, trimmed)
			lastEmpty = false
		}
	}
	return strings.TrimSpace(strings.Join(res, "\n")) + "\n"
}

func formatStackTitle(s string) string {
	switch s {
	case "go":
		return "Go Ecosystem"
	case "node":
		return "Node.js / TypeScript / Next.js Ecosystem"
	case "python":
		return "Python Ecosystem"
	case "rust":
		return "Rust Ecosystem"
	case "java":
		return "Java / JVM Ecosystem"
	case "cpp":
		return "C / C++ / CMake Ecosystem"
	default:
		return strings.ToUpper(s) + " Ecosystem"
	}
}

func writeIgnoreTargetFile(targetFile, content string, existed, force, appendMode bool, reader *bufio.Reader, label string) {
	if existed && !force && !appendMode {
		fmt.Printf(color.HiYellowString("File %s already exists. [O]verwrite / [A]ppend / [S]kip? (default O): "), label)
		ans, _ := reader.ReadString('\n')
		choice := strings.TrimSpace(strings.ToLower(ans))
		if choice == "s" || choice == "skip" {
			color.Yellow("Skipped %s", label)
			return
		}
		if choice == "a" || choice == "append" {
			appendMode = true
		}
	}

	if appendMode && existed {
		f, err := os.OpenFile(targetFile, os.O_APPEND|os.O_WRONLY, 0644)
		if err != nil {
			color.Red("Failed to append to %s: %v", label, err)
			return
		}
		defer f.Close()
		_, _ = f.WriteString("\n" + content)
		color.Green("✔ Appended polyglot rules to %s", label)
	} else {
		err := os.WriteFile(targetFile, []byte(content), 0644)
		if err != nil {
			color.Red("Failed to write %s: %v", label, err)
			return
		}
		color.Green("✔ Successfully generated %s", label)
	}
}

func renderIgnorePlanBox(plan IgnorePlan) {
	color.Cyan("╭─────────────────────────────────────────────────────────────╮")
	color.Cyan("│                  POLYGLOT IGNORE GENERATOR                  │")
	color.Cyan("├───────────────────────┬─────────────────────────────────────┤")

	targetDir := plan.TargetDir
	if len(targetDir) > 35 {
		targetDir = "..." + targetDir[len(targetDir)-32:]
	}
	fmt.Printf(color.CyanString("│")+" %-21s "+color.CyanString("│")+" %-35s "+color.CyanString("│\n"), "Target Directory", color.HiWhiteString(targetDir))

	var stackNames []string
	for _, s := range plan.DetectedStacks {
		stackNames = append(stackNames, strings.ToUpper(s))
	}
	stackStr := strings.Join(stackNames, ", ")
	if len(stackStr) > 35 {
		stackStr = stackStr[:32] + "..."
	}
	fmt.Printf(color.CyanString("│")+" %-21s "+color.CyanString("│")+" %-35s "+color.CyanString("│\n"), "Detected Stacks", color.HiCyanString(stackStr))

	targets := ".gitignore, .dockerignore"
	if ignoreGitOnly {
		targets = ".gitignore only"
	} else if ignoreDockerOnly {
		targets = ".dockerignore only"
	}
	fmt.Printf(color.CyanString("│")+" %-21s "+color.CyanString("│")+" %-35s "+color.CyanString("│\n"), "Target Artifacts", color.HiYellowString(targets))

	gitRulesStr := fmt.Sprintf("%d ignore rules", plan.GitignoreRules)
	if plan.GitignoreExisted {
		gitRulesStr += " (Exists)"
	}
	fmt.Printf(color.CyanString("│")+" %-21s "+color.CyanString("│")+" %-35s "+color.CyanString("│\n"), ".gitignore Status", color.HiWhiteString(gitRulesStr))

	dockerRulesStr := fmt.Sprintf("%d exclusion rules", plan.DockerRules)
	if plan.DockerExisted {
		dockerRulesStr += " (Exists)"
	}
	fmt.Printf(color.CyanString("│")+" %-21s "+color.CyanString("│")+" %-35s "+color.CyanString("│\n"), ".dockerignore Status", color.HiWhiteString(dockerRulesStr))

	color.Cyan("╰───────────────────────┴─────────────────────────────────────╯\n")
}
